import QRCode from 'qrcode';

/**
 * Minimal, dependency-free QR → PDF generator.
 *
 * QR modules are emitted as vector rectangles (no raster scaling), with the
 * standard 4-module quiet zone, so prints remain crisp and scannable. One A4
 * page per QR item; bulk exports are one multi-page PDF.
 */

export interface QrPdfItem {
  title: string;
  url: string;
}

const PAGE_WIDTH = 595.28;
const PAGE_HEIGHT = 841.89;
const MARGIN = 48;
const QR_SIZE = 360;
const QUIET_MODULES = 4;

/** PDF literal strings: ASCII only, balanced escapes. */
function pdfText(value: string): string {
  return value
    .replace(/[^\x20-\x7e]/g, '?')
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)');
}

function wrapText(value: string, maxChars: number): string[] {
  const text = value.replace(/\s+/g, ' ').trim();
  if (!text) return [''];
  const lines: string[] = [];
  let current = '';
  for (const word of text.split(' ')) {
    if (word.length > maxChars) {
      if (current) {
        lines.push(current);
        current = '';
      }
      for (let i = 0; i < word.length; i += maxChars) {
        lines.push(word.slice(i, i + maxChars));
      }
      continue;
    }
    const next = current ? `${current} ${word}` : word;
    if (next.length > maxChars) {
      if (current) lines.push(current);
      current = word;
    } else {
      current = next;
    }
  }
  if (current) lines.push(current);
  return lines;
}

function textCommand(
  x: number,
  y: number,
  size: number,
  value: string,
  font: 'F1' | 'F2' = 'F1',
  gray = 0
): string {
  return `BT ${gray} ${gray} ${gray} rg /${font} ${size} Tf 1 0 0 1 ${x.toFixed(2)} ${y.toFixed(2)} Tm (${pdfText(value)}) Tj ET`;
}

function buildPageContent(item: QrPdfItem): string {
  const commands: string[] = [];
  commands.push('1 1 1 rg 0 0 595.28 841.89 re f');

  commands.push(textCommand(MARGIN, 800, 9, 'TAPREVIA', 'F2', 0.45));
  const titleLines = wrapText(item.title || 'QR Code', 42).slice(0, 2);
  titleLines.forEach((line, index) => {
    commands.push(textCommand(MARGIN, 772 - index * 24, 18, line, 'F2'));
  });

  // Vector QR with 4-module quiet zone, centered horizontally.
  const qr = QRCode.create(item.url, { errorCorrectionLevel: 'M' });
  const modules = qr.modules.size + QUIET_MODULES * 2;
  const moduleSize = QR_SIZE / modules;
  const qrX = (PAGE_WIDTH - QR_SIZE) / 2;
  const qrY = 350;

  commands.push('0 0 0 rg');
  const rects: string[] = [];
  for (let row = 0; row < qr.modules.size; row += 1) {
    for (let col = 0; col < qr.modules.size; col += 1) {
      if (!qr.modules.get(row, col)) continue;
      const x = qrX + (col + QUIET_MODULES) * moduleSize;
      const y = qrY + (qr.modules.size - 1 - row + QUIET_MODULES) * moduleSize;
      rects.push(
        `${x.toFixed(3)} ${y.toFixed(3)} ${moduleSize.toFixed(3)} ${moduleSize.toFixed(3)} re`
      );
    }
  }
  commands.push(`${rects.join(' ')} f`);

  commands.push(textCommand(MARGIN, 318, 9, 'PERMANENT QR DESTINATION', 'F2', 0.45));
  const urlLines = wrapText(item.url, 100).slice(0, 22);
  urlLines.forEach((line, index) => {
    commands.push(textCommand(MARGIN, 300 - index * 10, 8, line, 'F1', 0.15));
  });

  commands.push(textCommand(MARGIN, 52, 8, 'Generated by Taprevia', 'F1', 0.55));
  return commands.join('\n');
}

export async function generateQrPdf(items: QrPdfItem[]): Promise<Blob> {
  if (!items.length) throw new Error('generateQrPdf: at least one QR is required');

  // Objects: 1 catalog, 2 pages, 3 Helvetica, 4 Helvetica-Bold, then page/content pairs.
  const objects: string[] = [];
  objects.push('<< /Type /Catalog /Pages 2 0 R >>');
  objects.push(''); // pages object filled after page ids are known
  objects.push('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>');
  objects.push('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>');

  const pageIds: number[] = [];
  for (const item of items) {
    const content = buildPageContent(item);
    const pageId = objects.length + 1;
    const contentId = pageId + 1;
    pageIds.push(pageId);
    objects.push(
      `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${PAGE_WIDTH} ${PAGE_HEIGHT}] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents ${contentId} 0 R >>`
    );
    objects.push(`<< /Length ${content.length} >>\nstream\n${content}\nendstream`);
  }
  objects[1] = `<< /Type /Pages /Kids [${pageIds.map((id) => `${id} 0 R`).join(' ')}] /Count ${pageIds.length} >>`;

  let pdf = '%PDF-1.4\n';
  const offsets: number[] = [0];
  objects.forEach((body, index) => {
    offsets[index + 1] = pdf.length;
    pdf += `${index + 1} 0 obj\n${body}\nendobj\n`;
  });
  const xrefStart = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (let i = 1; i <= objects.length; i += 1) {
    pdf += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF`;

  // All content is ASCII by construction, so string length equals byte length.
  return new Blob([pdf], { type: 'application/pdf' });
}

/** Generate and trigger a single PDF download (single or multi-page). */
export async function downloadQrPdf(items: QrPdfItem[], filename: string): Promise<void> {
  if (typeof window === 'undefined') throw new Error('downloadQrPdf requires a browser');
  const blob = await generateQrPdf(items);
  const href = URL.createObjectURL(blob);
  try {
    const anchor = document.createElement('a');
    anchor.href = href;
    anchor.download = filename.endsWith('.pdf') ? filename : `${filename}.pdf`;
    document.body.appendChild(anchor);
    anchor.click();
    anchor.remove();
  } finally {
    window.setTimeout(() => URL.revokeObjectURL(href), 1000);
  }
}
